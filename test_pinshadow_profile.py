class TestFreeZone(unittest.TestCase):
    def test_no_shadowAnywhere(self):
        fracs = [0.0] * 360
        self.assertEqual(pp.free_zone(fracs), ([0.0, 360.0], 360.0))

    def test_wraparound_example(self):
        # shadow-free bins 117..359 plus 0..43  ->  ([117, 44], 287)
        fracs = [0.02] * 360
        for i in chain(range(117, 360), range(0, 44)):
            fracs[i] = 0.0
        self.assertEqual(pp.free_zone(fracs), ([117.0, 44.0], 287.0))

    def test_no_free_stretch(self):
        self.assertIsNone(pp.free_zone([0.01] * 360))

    def test_non_wrapping(self):
        fracs = [0.02] * 360
        for i in range(100, 201):
            fracs[i] = 0.0
        self.assertEqual(pp.free_zone(fracs), ([100.0, 201.0], 101.0))

    def test_tie_returns_first_after_shadowed_bin(self):
        fracs = [0.02] * 360
        for i in chain(range(10, 50), range(100, 140)):
            fracs[i] = 0.0
        self.assertEqual(pp.free_zone(fracs), ([10.0, 50.0], 40.0))


