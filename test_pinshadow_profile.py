def _f32(v):
    """float64 -> the float32 the visualizer's Float32Array would store."""
    return struct.unpack("<f", struct.pack("<f", v))[0]


def _brute_free_zone(fracs):
    """Independent reference implementation of free_zone (brute force)."""
    free = [f <= 0.0 for f in fracs]
    if all(free):
        return ([0.0, 360.0], 360.0)
    if not any(free):
        return None
    best = None
    for start in range(360):
        if not (free[start] and not free[start - 1]):
            continue
        length, i = 0, start
        while free[i % 360]:
            length, i = length + 1, i + 1
        if best is None or length > best[1]:
            best = (start, length)
    s, length = best
    return ([float(s), float((s + length) % 360)], float(length))


